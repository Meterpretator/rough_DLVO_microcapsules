"""
Единый модуль физических констант и параметров DLVO.

Используется в:
    - dlvo_calc_v2.py
    - DLVO_sphere_smooth.py

Все параметры сгруппированы по смыслу. Единицы — СИ.
"""

import numpy as np

# ============================================================
# 1. ФУНДАМЕНТАЛЬНЫЕ ФИЗИЧЕСКИЕ КОНСТАНТЫ
# ============================================================

k_B = 1.380649e-23          # постоянная Больцмана [Дж/К]
e = 1.602176634e-19         # элементарный заряд [Кл]
epsilon_0 = 8.854187817e-12 # электрическая постоянная [Ф/м]
N_A = 6.02214076e23         # число Авогадро [1/моль]


# ============================================================
# 2. ПАРАМЕТРЫ СРЕДЫ (ВОДА ПРИ 298 К)
# ============================================================

T = 298.0           # температура [К]
epsilon_r = 78.5            # относительная диэлектрическая проницаемость
kT = k_B * T       # тепловая энергия [Дж]


# ============================================================
# 3. ПАРАМЕТРЫ DLVO
# ============================================================

A_H = 1e-20                 # константа Гамакера [Дж]
zeta1 = -25e-3              # потенциал поверхности 1 [В]
zeta2 = -15e-3              # потенциал поверхности 2 [В]
ionic_strength = 1.0        # ионная сила [моль/м³] (= 1 мМ для 1:1)

d_min = 0.3e-9              # минимальный зазор (отсечка) [м]


# ============================================================
# 4. ПАРАМЕТРЫ ГЕНЕРАЦИИ ПОВЕРХНОСТИ
# ============================================================

N = 1024                    # размер сетки
Lx = 1e-6                   # размер области по x [м]
Ly = 1e-6                   # размер области по y [м]
sigma_f = 2e-9              # амплитуда шероховатости [м]
xi = 1e-8                   # корреляционная длина [м]
H0 = 10e-9                  # среднее расстояние [м]

seed = None                 # seed для воспроизводимости (None = случайный)


# ============================================================
# 5. ПАРАМЕТРЫ СФЕРЫ (для DLVO_sphere_smooth)
# ============================================================

R = 320e-9                  # радиус сферы [м]


# ============================================================
# 6. ДИАПАЗОН РАСЧЁТА
# ============================================================

H0_min = 0.5e-9             # минимальное среднее расстояние [м]
H0_max = 30e-9              # максимальное среднее расстояние [м]
H0_n_points = 100           # число точек по H0


# ============================================================
# 7. ПАРАМЕТРЫ ВИЗУАЛИЗАЦИИ (единый стиль для всех фигур)
# ============================================================

SUPTITLE_Y = 0.98           # позиция suptitle по вертикали
SUPTITLE_SIZE = 11          # размер шрифта suptitle
RECT_TOP = 0.93             # верхняя граница для tight_layout
FIG_WIDTH = 14              # ширина фигуры по умолчанию [дюймы]
FIG_HEIGHT = 5.5            # высота фигуры по умолчанию [дюймы]


# ============================================================
# 8. ПРОИЗВОДНЫЕ ПАРАМЕТРЫ (вычисляются автоматически)
# ============================================================

def get_derived_params():
    """
    Возвращает словарь производных параметров:
        kappa, lambda_D, gamma1, gamma2, n0, kT
    """
    # Обратная дебаевская длина
    kappa = np.sqrt(
        (2 * e ** 2 * N_A * ionic_strength)
        / (epsilon_0 * epsilon_r * k_B * T_default)
    )
    lambda_D = 1.0 / kappa

    # Параметры gamma
    gamma1 = np.tanh(e * zeta1 / (4 * k_B * T_default))
    gamma2 = np.tanh(e * zeta2 / (4 * k_B * T_default))

    # Концентрация ионов (для 1:1 электролита, полная)
    n0 = 2 * N_A * ionic_strength

    return {
        'kappa': kappa,
        'lambda_D': lambda_D,
        'gamma1': gamma1,
        'gamma2': gamma2,
        'n0': n0,
        'kT': kT,
    }


# ============================================================
# 9. ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ ПЕЧАТИ ПАРАМЕТРОВ
# ============================================================

def print_params():
    """Печатает все параметры и производные величины."""
    derived = get_derived_params()

    print("=" * 70)
    print("ПАРАМЕТРЫ DLVO (dlvo_params.py)")
    print("=" * 70)

    print("\n--- Константы ---")
    print(f"  k_B = {k_B:.6e} Дж/К")
    print(f"  e   = {e:.6e} Кл")
    print(f"  ε₀  = {epsilon_0:.6e} Ф/м")
    print(f"  N_A = {N_A:.6e} 1/моль")

    print("\n--- Среда ---")
    print(f"  T = {T_default:.1f} К")
    print(f"  ε_r = {epsilon_r:.2f}")
    print(f"  kT = {kT:.6e} Дж")

    print("\n--- DLVO ---")
    print(f"  A_H = {A_H:.2e} Дж")
    print(f"  ζ₁ = {zeta1*1000:.1f} мВ")
    print(f"  ζ₂ = {zeta2*1000:.1f} мВ")
    print(f"  I = {ionic_strength:.4f} моль/м³ ({ionic_strength/1000:.6f} М)")
    print(f"  d_min = {d_min*1e9:.2f} нм")

    print("\n--- Производные ---")
    print(f"  κ = {derived['kappa']:.4e} 1/м")
    print(f"  λ_D = {derived['lambda_D']*1e9:.2f} нм")
    print(f"  γ₁ = {derived['gamma1']:.4f}")
    print(f"  γ₂ = {derived['gamma2']:.4f}")
    print(f"  n0 = {derived['n0']:.4e} 1/м³")

    print("\n--- Поверхность ---")
    print(f"  N = {N}")
    print(f"  Lx = {Lx*1e9:.1f} нм, Ly = {Ly*1e9:.1f} нм")
    print(f"  σ_f = {sigma_f*1e9:.2f} нм")
    print(f"  ξ = {xi*1e9:.2f} нм")
    print(f"  H0 = {H0*1e9:.2f} нм")

    print("\n--- Сфера ---")
    print(f"  R = {R*1e9:.1f} нм")

    print("\n--- Диапазон H0 ---")
    print(f"  от {H0_min*1e9:.2f} до {H0_max*1e9:.2f} нм, {H0_n_points} точек")