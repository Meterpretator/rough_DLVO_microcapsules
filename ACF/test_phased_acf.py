import numpy as np
import matplotlib.pyplot as plt

from generate_surface.grids.k_grid import build_fft_k_grid


# ============================================================
# ПАРАМЕТРЫ
# ============================================================
N = 128
Lx, Ly = 20.0, 20.0

sigma = 1.0

# Параметры фазы для случая 2b
x0 = Lx / 4
y0 = Ly / 4

dx = Lx / N
dy = Ly / N


# ============================================================
# 1. СЕТКА r-ПРОСТРАНСТВА
# ============================================================
# Центрированная сетка:
#
#       [-L/2, L/2)
#
# Это удобно для визуализации поверхности.

x = np.arange(N) * dx - Lx / 2
y = np.arange(N) * dy - Ly / 2

X, Y = np.meshgrid(x, y, indexing='ij')


# ============================================================
# 2. СЕТКА k-ПРОСТРАНСТВА
# ============================================================
KX, KY, K, kx, ky = build_fft_k_grid(
    N, N, dx, dy
)


# ============================================================
# 3. АМПЛИТУДНЫЙ СПЕКТР
# ============================================================
#
# A(kx, ky) =
#
#       2*pi*sigma^2 * exp[-sigma^2(kx^2 + ky^2)/2]
#
# Это аналитический Фурье-образ центрированной
# двумерной гауссовой функции.
#
# ============================================================

A = (
    2.0
    * np.pi
    * sigma**2
    * np.exp(
        -0.5
        * sigma**2
        * (KX**2 + KY**2)
    )
)


# ============================================================
# ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ:
# восстановление поверхности из спектра
# ============================================================

def spectrum_to_surface(Z):
    """
    Z(kx,ky) -- непрерывный спектр.

    FFT хранит дискретную сумму, поэтому перед ifft2
    необходимо убрать множитель dx*dy:

        F_fft = Z / (dx*dy)

    """
    return np.fft.ifft2(
        Z / (dx * dy)
    )


# ============================================================
# ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ:
# АКФ через теорему Винера–Хинчина
# ============================================================

def autocorrelation_wiener_hinchen(surface):
    """
    Периодическая дискретная АКФ:

        C = IFFT( |FFT(f)|^2 )

    Для получения корреляции в физических единицах
    учитываем площадь элементарной ячейки.

    Нормированная АКФ:
        C_norm = C / C(0)
    """

    F = np.fft.fft2(surface)

    # Дискретная АКФ
    C = np.fft.ifft2(
        np.abs(F)**2
    ).real

    # Нормировка к C(0)
    C_norm = C / C[0, 0]

    return C, C_norm


# ============================================================
# ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ:
# ПРЯМАЯ ПРОВЕРКА АКФ
# ============================================================

def autocorrelation_direct(surface):
    """
    Прямая периодическая автокорреляция.

    Для каждого сдвига (m,n):

        C[m,n] =
            sum f[i,j] f[i+m,j+n]

    Реализуем через FFT, но с точки зрения определения
    это именно периодическая корреляция.
    """

    F = np.fft.fft2(surface)

    C = np.fft.ifft2(
        F * np.conjugate(F)
    ).real

    return C


# ============================================================
# 4. СЛУЧАЙ 2a
#
# psi(kx,ky) = 0
#
# Z(kx,ky) = A(kx,ky)
# ============================================================

print("\n" + "=" * 70)
print("СЛУЧАЙ 2a: psi(kx,ky) = 0")
print("=" * 70)

psi1 = np.zeros_like(KX)

Z1 = A * np.exp(-1j * psi1)

# Поверхность
f1_complex = spectrum_to_surface(Z1)

# Из-за симметрии спектра поверхность должна быть
# вещественной с погрешностью округления.
f1 = f1_complex.real

print(f"Максимальная мнимая часть f1: "
      f"{np.max(np.abs(f1_complex.imag)):.3e}")

print(f"Максимум f1: {f1.max():.6f}")
print(f"Минимум f1: {f1.min():.6f}")


# АКФ через Винера–Хинчина
ACF1, ACF1_norm = autocorrelation_wiener_hinchen(f1)

# Прямая проверка
ACF1_direct = autocorrelation_direct(f1)

# Сравниваем
acf1_difference = np.max(
    np.abs(ACF1 - ACF1_direct)
)

print(
    f"Максимальная разница между двумя "
    f"расчётами АКФ: {acf1_difference:.3e}"
)


# ============================================================
# 5. СЛУЧАЙ 2b
#
# psi(kx,ky) =
#
# i*cos(x0*kx)
# + i*cos(y0*ky)
# + sin(x0*kx)
# + sin(y0*ky)
#
# Z = A * exp[-i*psi]
# ============================================================

print("\n" + "=" * 70)
print("СЛУЧАЙ 2b: заданная psi(kx,ky)")
print("=" * 70)

psi2 = (
    1j * np.cos(x0 * KX)
    + 1j * np.cos(y0 * KY)
    + np.sin(x0 * KX)
    + np.sin(y0 * KY)
)

Z2 = A * np.exp(-1j * psi2)


# ------------------------------------------------------------
# ВАЖНО:
#
# Здесь psi2 комплексная.
#
# Поэтому:
#
# exp(-i*psi2)
#
# вообще говоря, НЕ является чисто фазовым множителем
# и меняет модуль Z2.
#
# Мы именно это и сохраняем, поскольку это задано
# в условии задачи.
# ------------------------------------------------------------

print(
    f"min |Z2|: {np.min(np.abs(Z2)):.6e}"
)

print(
    f"max |Z2|: {np.max(np.abs(Z2)):.6e}"
)


# Поверхность
f2_complex = spectrum_to_surface(Z2)

f2 = f2_complex.real

print(
    f"Максимальная мнимая часть f2: "
    f"{np.max(np.abs(f2_complex.imag)):.3e}"
)

print(
    f"Максимум f2: {f2.max():.6f}"
)

print(
    f"Минимум f2: {f2.min():.6f}"
)


# АКФ
ACF2, ACF2_norm = autocorrelation_wiener_hinchen(f2)

# Прямая проверка
ACF2_direct = autocorrelation_direct(f2)

acf2_difference = np.max(
    np.abs(ACF2 - ACF2_direct)
)

print(
    f"Максимальная разница между двумя "
    f"расчётами АКФ: {acf2_difference:.3e}"
)


# ============================================================
# 6. fftshift ТОЛЬКО ДЛЯ ВИЗУАЛИЗАЦИИ
# ============================================================

f1_shifted = np.fft.fftshift(f1)
f2_shifted = np.fft.fftshift(f2)

ACF1_shifted = np.fft.fftshift(ACF1_norm)
ACF2_shifted = np.fft.fftshift(ACF2_norm)


